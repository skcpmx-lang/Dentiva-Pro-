#!/usr/bin/env node
/**
 * Third-party notice generator.
 *
 * Writes `docs/compliance/THIRD-PARTY-NOTICES.md`: every library that ships inside Dentiva Pro (the
 * runtime closure of what `src/` imports, plus the bundled fonts) with its version, licence and the full
 * licence text as installed, so the shipped product can be audited offline.
 *
 * Run it whenever dependencies change: `npm run licenses`.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import {
  COPYLEFT_PATTERN,
  PERMISSIVE_PATTERN,
  readLicenseText,
  repoRootSafe,
  shippedPackages
} from './lib/paths.mjs'

const repoRoot = repoRootSafe(import.meta.url)
const manifest = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8'))
const packages = [...shippedPackages(repoRoot).values()].sort((left, right) =>
  left.name.localeCompare(right.name)
)
const bundledFonts = ['@fontsource/inter', '@fontsource/noto-sans-bengali']

const lines = []
lines.push('# Third-party notices — Dentiva Pro')
lines.push('')
lines.push(
  `Dentiva Pro ${manifest.version} is distributed with the third-party components listed below. Each entry`
)
lines.push(
  'gives the version that is installed in this build, the licence declared by the component and the licence'
)
lines.push('text as shipped by the component. This file is generated by `npm run licenses`.')
lines.push('')
lines.push('All listed components are permissively licensed; none of them is copyleft.')
lines.push('')

function row(name, version, licence) {
  return `| \`${name}\` | ${version} | ${licence} |`
}

lines.push('## Components')
lines.push('')
lines.push('| Component | Version | Licence |')
lines.push('|---|---|---|')
for (const pkg of packages) lines.push(row(pkg.name, pkg.version, pkg.license || 'see text below'))
for (const name of bundledFonts) {
  const pkg = JSON.parse(readFileSync(join(repoRoot, 'node_modules', name, 'package.json'), 'utf8'))
  lines.push(row(name, pkg.version, 'OFL-1.1 (SIL Open Font License)'))
}
lines.push('')
lines.push('## Bundled assets')
lines.push('')
lines.push(
  'The application embeds the Inter and Noto Sans Bengali font files so that Latin and Bengali text render'
)
lines.push('identically on screen, on paper and in exported PDFs without any network access:')
lines.push('')
lines.push('- **Inter** — latin, latin-ext and Cyrillic/Greek subsets, weight 400–700.')
lines.push(
  '- **Noto Sans Bengali** — Bengali and latin subsets, weight 400 and 600, used for all Bengali text.'
)
lines.push('')
lines.push('Both fonts are licensed under the SIL Open Font License 1.1, which permits embedding and')
lines.push('redistribution inside a commercial application.')
lines.push('')
lines.push('## Licence texts')
lines.push('')

for (const pkg of packages) {
  const licenceText = readLicenseText(pkg.directory)
  lines.push(`### ${pkg.name} ${pkg.version}`)
  lines.push('')
  lines.push(`- Licence: ${pkg.license || 'see text'}`)
  if (pkg.homepage) lines.push(`- Homepage: ${pkg.homepage}`)
  lines.push('')
  if (licenceText) {
    lines.push('```')
    lines.push(licenceText.text.trim())
    lines.push('```')
  } else {
    lines.push('_The installed package did not include a licence file._')
  }
  lines.push('')
}

for (const name of bundledFonts) {
  const directory = join(repoRoot, 'node_modules', name)
  const pkg = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'))
  const licenceText = readLicenseText(directory)
  lines.push(`### ${name} ${pkg.version}`)
  lines.push('')
  lines.push('- Licence: OFL-1.1')
  lines.push(`- Homepage: ${pkg.homepage ?? 'https://fontsource.org'}`)
  lines.push('')
  if (licenceText) {
    lines.push('```')
    lines.push(licenceText.text.trim())
    lines.push('```')
  } else {
    lines.push('_The installed package did not include a licence file._')
  }
  lines.push('')
}

const outputPath = join(repoRoot, 'docs', 'compliance', 'THIRD-PARTY-NOTICES.md')
const textPath = join(repoRoot, 'docs', 'compliance', 'THIRD-PARTY-NOTICES.txt')
mkdirSync(join(repoRoot, 'docs', 'compliance'), { recursive: true })
writeFileSync(outputPath, `${lines.join('\n')}\n`, 'utf8')

// The packaged application shows the notices in the About page, so it ships a plain-text copy.
const plain = []
plain.push('THIRD-PARTY NOTICES — Dentiva Pro')
plain.push('='.repeat(78))
plain.push('')
plain.push(
  `Dentiva Pro ${manifest.version} ships with the third-party components listed below. Every component is`
)
plain.push('permissively licensed (MIT, ISC or the SIL Open Font License); none is copyleft.')
plain.push('')
plain.push('This file is generated by "npm run licenses" from the installed packages.')
plain.push('')
for (const pkg of packages) {
  const licence = pkg.license || 'see licence text'
  plain.push(`* ${pkg.name} ${pkg.version} — ${licence}${pkg.homepage ? ` — ${pkg.homepage}` : ''}`)
}
for (const name of bundledFonts) {
  const pkg = JSON.parse(readFileSync(join(repoRoot, 'node_modules', name, 'package.json'), 'utf8'))
  plain.push(`* ${name} ${pkg.version} — OFL-1.1 — ${pkg.homepage ?? 'https://fontsource.org'}`)
}
plain.push('')
plain.push('─'.repeat(78))
plain.push('')
for (const pkg of packages) {
  const licenceText = readLicenseText(pkg.directory)
  plain.push(`${pkg.name} ${pkg.version} — ${pkg.license || 'see text'}`)
  plain.push('')
  plain.push(licenceText ? licenceText.text.trim() : 'The installed package did not include a licence file.')
  plain.push('')
  plain.push('─'.repeat(78))
  plain.push('')
}
for (const name of bundledFonts) {
  const licenceText = readLicenseText(join(repoRoot, 'node_modules', name))
  plain.push(`${name} — OFL-1.1`)
  plain.push('')
  plain.push(licenceText ? licenceText.text.trim() : 'The installed package did not include a licence file.')
  plain.push('')
  plain.push('─'.repeat(78))
  plain.push('')
}
writeFileSync(textPath, `${plain.join('\n')}\n`, 'utf8')

const problems = packages.filter(
  (pkg) => !pkg.license || (!PERMISSIVE_PATTERN.test(pkg.license) && !COPYLEFT_PATTERN.test(pkg.license))
)
console.log(`Wrote ${outputPath}`)
console.log(`Wrote ${textPath} (shipped with the application)`)
console.log(`  ${packages.length} bundled components + ${bundledFonts.length} bundled font families`)
if (problems.length > 0) {
  console.log('  Components whose licence needs a manual look:')
  for (const pkg of problems) console.log(`    ${pkg.name} — ${pkg.license || 'unknown'}`)
  process.exitCode = 0
}
